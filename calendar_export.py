def preview_schedule_text(
    session: Session,
) -> str:
    """
    Generate a text preview of the schedule grouped by day.

    Args:
        session: The planning session

    Returns:
        Formatted text representation of the schedule
    """
    if not session.schedule:
        return "No tasks scheduled yet."

    task_lookup = {task.id: task for task in session.task_blocks}

    # Group by date
    by_date = {}
    for scheduled in session.schedule:
        date_key = scheduled.start.date()
        if date_key not in by_date:
            by_date[date_key] = []
        by_date[date_key].append(scheduled)

    # Sort dates
    sorted_dates = sorted(by_date.keys())

    lines = []
    for date in sorted_dates:
        lines.append(f"\n📅 {date.strftime('%A, %B %d, %Y')}")
        lines.append("-" * 40)

        # Sort by start time
        day_schedule = sorted(by_date[date], key=lambda s: s.start)

        for scheduled in day_schedule:
            task = task_lookup.get(scheduled.task_id)
            if task:
                start_time = scheduled.start.strftime("%H:%M")
                end_time = scheduled.end.strftime("%H:%M")
                priority_icon = "🔴" if task.priority == "must" else "🟡"
                lines.append(f"  {priority_icon} {start_time} - {end_time}: {task.title}")

                # Add resources if available
                if task.resources:
                    for res in task.resources:
                        lines.append(f"      📎 {res.title}: {res.url}")

    return "\n".join(lines)
